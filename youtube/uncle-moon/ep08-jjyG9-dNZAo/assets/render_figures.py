"""Render the episode's seven explanatory diagrams."""
import json
import xml.etree.ElementTree as ET
from pathlib import Path
from svg_engine import Diagram, FIGURES, convert

ROOT = Path(__file__).resolve().parent


def row(d, labels, y=120):
    nodes = [d.box(35+i*240,y,210,ls,c) for i,(ls,c) in enumerate(zip(labels,['blue','purple','orange','green']))]
    for a,b in zip(nodes,nodes[1:]): d.right(a,b)


